// Count steps in one loop
public class Main {
    public static void main(String[] args) {
        int steps = 0;
        // Time complexity: O(n), where n is the loop limit.
        for (int i = 1; i <= 10; i++) {
            steps++;
        }
        System.out.println("Steps: " + steps);
    }
}
